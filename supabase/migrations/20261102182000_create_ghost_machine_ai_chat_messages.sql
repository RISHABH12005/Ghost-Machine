CREATE TABLE IF NOT EXISTS public.ghost_machine_ai_chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  github_login text NOT NULL,
  repository_full_name text NOT NULL,
  conversation_id text NOT NULL DEFAULT 'default',
  role text NOT NULL CHECK (role IN ('user', 'assistant')),
  content text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ghost_machine_ai_chat_history_idx
  ON public.ghost_machine_ai_chat_messages (github_login, repository_full_name, conversation_id, id);

ALTER TABLE public.ghost_machine_ai_chat_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ghost_machine_ai_chat_messages FROM anon, authenticated;

DROP POLICY IF EXISTS deny_browser_chat_history_access ON public.ghost_machine_ai_chat_messages;
CREATE POLICY deny_browser_chat_history_access
  ON public.ghost_machine_ai_chat_messages
  FOR ALL TO anon, authenticated
  USING (false)
  WITH CHECK (false);
